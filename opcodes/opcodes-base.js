// opcodes-base.js - Basic opcodes (0x00-0x3F)
import { cpuOps } from '../cpu-operations.js';

export const baseOpcodes = {
  0x00: function(p){p.clock.c += 4;},
  0x01: function(p){cpuOps.LDrrnn(p, 'B', 'C');},
  0x02: function(p){cpuOps.LDrrar(p, 'B', 'C', 'A');},
  0x03: function(p){cpuOps.INCrr(p, 'B', 'C');},
  0x04: function(p){cpuOps.INCr(p, 'B');},
  0x05: function(p){cpuOps.DECr(p, 'B');},
  0x06: function(p){cpuOps.LDrn(p, 'B');},
  0x07: function(p){var out=p.r.A & 0x80?1:0; out ? p.r.F=0x10:p.r.F=0; p.wr('A', ((p.r.A<<1)+out)&0xFF);p.clock.c+=4;},
  0x08: function(p){cpuOps.LDnnsp(p);},
  0x09: function(p){cpuOps.ADDrrrr(p, 'H', 'L', 'B', 'C');},
  0x0A: function(p){cpuOps.LDrrra(p, 'A', 'B', 'C');},
  0x0B: function(p){cpuOps.DECrr(p, 'B', 'C');},
  0x0C: function(p){cpuOps.INCr(p, 'C');},
  0x0D: function(p){cpuOps.DECr(p, 'C');},
  0x0E: function(p){cpuOps.LDrn(p, 'C');},
  0x0F: function(p){var out=p.r.A & 0x01; out ? p.r.F=0x10:p.r.F=0; p.wr('A', (p.r.A>>1)|(out*0x80));p.clock.c+=4;},

  0x10: function(p){p.r.pc++;p.clock.c+=4;},
  0x11: function(p){cpuOps.LDrrnn(p, 'D', 'E');},
  0x12: function(p){cpuOps.LDrrar(p, 'D', 'E', 'A');},
  0x13: function(p){cpuOps.INCrr(p, 'D', 'E');},
  0x14: function(p){cpuOps.INCr(p, 'D');},
  0x15: function(p){cpuOps.DECr(p, 'D');},
  0x16: function(p){cpuOps.LDrn(p, 'D');},
  0x17: function(p){var c = (p.r.F&0x10)?1:0;var out=p.r.A & 0x80?1:0; out ? p.r.F=0x10:p.r.F=0; p.wr('A',((p.r.A<<1)+c)&0xFF);p.clock.c+=4;},
  0x18: function(p){cpuOps.JRn(p);},
  0x19: function(p){cpuOps.ADDrrrr(p, 'H', 'L', 'D', 'E');},
  0x1A: function(p){cpuOps.LDrrra(p, 'A', 'D', 'E');},
  0x1B: function(p){cpuOps.DECrr(p, 'D', 'E');},
  0x1C: function(p){cpuOps.INCr(p, 'E');},
  0x1D: function(p){cpuOps.DECr(p, 'E');},
  0x1E: function(p){cpuOps.LDrn(p, 'E');},
  0x1F: function(p){var c = (p.r.F&0x10)?1:0;var out=p.r.A & 0x01; out ? p.r.F=0x10:p.r.F=0; p.wr('A', (p.r.A>>1)|(c*0x80));p.clock.c+=4;},

  0x20: function(p){cpuOps.JRccn(p, 'NZ');},
  0x21: function(p){cpuOps.LDrrnn(p, 'H', 'L');},
  0x22: function(p){cpuOps.LDrrar(p, 'H', 'L', 'A');cpuOps.INCrr(p, 'H', 'L');p.clock.c -= 8;},
  0x23: function(p){cpuOps.INCrr(p, 'H', 'L');},
  0x24: function(p){cpuOps.INCr(p, 'H');},
  0x25: function(p){cpuOps.DECr(p, 'H');},
  0x26: function(p){cpuOps.LDrn(p, 'H');},
  0x27: function(p){cpuOps.DAA(p);},
  0x28: function(p){cpuOps.JRccn(p, 'Z');},
  0x29: function(p){cpuOps.ADDrrrr(p, 'H', 'L', 'H', 'L');},
  0x2A: function(p){cpuOps.LDrrra(p, 'A', 'H', 'L');cpuOps.INCrr(p, 'H', 'L');p.clock.c -= 8;},
  0x2B: function(p){cpuOps.DECrr(p, 'H', 'L');},
  0x2C: function(p){cpuOps.INCr(p, 'L');},
  0x2D: function(p){cpuOps.DECr(p, 'L');},
  0x2E: function(p){cpuOps.LDrn(p, 'L');},
  0x2F: function(p){cpuOps.CPL(p);},

  0x30: function(p){cpuOps.JRccn(p, 'NC');},
  0x31: function(p){cpuOps.LDspnn(p);},
  0x32: function(p){cpuOps.LDrrar(p, 'H', 'L', 'A');cpuOps.DECrr(p, 'H', 'L');p.clock.c -= 8;},
  0x33: function(p){cpuOps.INCsp(p);},
  0x34: function(p){cpuOps.INCrra(p, 'H', 'L');},
  0x35: function(p){cpuOps.DECrra(p, 'H', 'L');},
  0x36: function(p){cpuOps.LDrran(p, 'H', 'L');},
  0x37: function(p){cpuOps.SCF(p);},
  0x38: function(p){cpuOps.JRccn(p, 'C');},
  0x39: function(p){cpuOps.ADDrrsp(p, 'H', 'L');},
  0x3A: function(p){cpuOps.LDrrra(p, 'A', 'H', 'L');cpuOps.DECrr(p, 'H', 'L');p.clock.c -= 8;},
  0x3B: function(p){cpuOps.DECsp(p);},
  0x3C: function(p){cpuOps.INCr(p, 'A');},
  0x3D: function(p){cpuOps.DECr(p, 'A');},
  0x3E: function(p){cpuOps.LDrn(p, 'A');},
  0x3F: function(p){cpuOps.CCF(p);}
};

